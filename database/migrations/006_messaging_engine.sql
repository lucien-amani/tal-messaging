-- Module 4 : Messaging Engine (envois, file d'attente, suivi). MySQL 8 / MariaDB 10.4+.
-- Un « envoi » (message_batches) regroupe les messages d'un Quick Send ; chaque destinataire a sa ligne dans messages.
-- Le nom du Sender ID est copié (snapshot) pour garder l'historique même si le Sender ID est retiré.

CREATE TABLE message_batches (
  id               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid             CHAR(36)        NOT NULL,
  organization_id  BIGINT UNSIGNED NOT NULL,
  sender_id_id     BIGINT UNSIGNED NULL,
  sender_name      VARCHAR(11)     NOT NULL,
  channel          ENUM('sms') NOT NULL DEFAULT 'sms',
  source           ENUM('quick_send','api','campaign') NOT NULL DEFAULT 'quick_send',
  body             VARCHAR(1600)   NOT NULL,
  total_messages   INT UNSIGNED    NOT NULL DEFAULT 0,
  total_segments   INT UNSIGNED    NOT NULL DEFAULT 0,
  scheduled_at     DATETIME        NULL,
  idempotency_key  VARCHAR(64)     NULL,
  created_by       BIGINT UNSIGNED NULL,
  created_at       DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_batch_uuid (uuid),
  UNIQUE KEY uq_batch_idem (organization_id, idempotency_key),
  KEY idx_batch_org (organization_id, created_at),
  CONSTRAINT fk_batch_org FOREIGN KEY (organization_id) REFERENCES organizations (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE messages (
  id                  BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  uuid                CHAR(36)        NOT NULL,
  organization_id     BIGINT UNSIGNED NOT NULL,
  batch_id            BIGINT UNSIGNED NULL,
  contact_id          BIGINT UNSIGNED NULL,
  sender_id_id        BIGINT UNSIGNED NULL,
  sender_name         VARCHAR(11)     NOT NULL,
  to_e164             VARCHAR(20)     NOT NULL,
  country             CHAR(2)         NULL,
  operator            VARCHAR(20)     NULL,
  body                VARCHAR(1600)   NOT NULL,
  encoding            ENUM('gsm7','ucs2') NOT NULL DEFAULT 'gsm7',
  segments            TINYINT UNSIGNED NOT NULL DEFAULT 1,
  status              ENUM('queued','sending','sent','delivered','failed','cancelled') NOT NULL DEFAULT 'queued',
  error_code          VARCHAR(40)     NULL,
  error_message       VARCHAR(255)    NULL,
  provider            VARCHAR(30)     NULL,
  provider_message_id VARCHAR(80)     NULL,
  scheduled_at        DATETIME        NULL,
  next_attempt_at     DATETIME        NULL,
  attempts            TINYINT UNSIGNED NOT NULL DEFAULT 0,
  lock_token          CHAR(16)        NULL,
  locked_at           DATETIME        NULL,
  sent_at             DATETIME        NULL,
  delivered_at        DATETIME        NULL,
  created_by          BIGINT UNSIGNED NULL,
  created_at          DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_message_uuid (uuid),
  KEY idx_msg_org_created (organization_id, created_at),
  KEY idx_msg_org_status (organization_id, status, created_at),
  KEY idx_msg_batch (batch_id, status),
  KEY idx_msg_to (organization_id, to_e164),
  KEY idx_msg_due (status, scheduled_at, next_attempt_at),
  KEY idx_msg_lock (status, locked_at),
  CONSTRAINT fk_msg_org FOREIGN KEY (organization_id) REFERENCES organizations (id),
  CONSTRAINT fk_msg_batch FOREIGN KEY (batch_id) REFERENCES message_batches (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
